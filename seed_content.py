def main():
    with get_db() as conn:
        for n in JUNK_CLASSES:
            conn.execute("DELETE FROM class_features WHERE class_id IN (SELECT id FROM classes WHERE lower(name)=lower(?))", (n,))
            conn.execute("DELETE FROM classes WHERE lower(name)=lower(?)", (n,))
        for n in JUNK_BACKGROUNDS:
            conn.execute("DELETE FROM background_choice_groups WHERE background_id IN (SELECT id FROM backgrounds WHERE name=?)", (n,))
            conn.execute("DELETE FROM backgrounds WHERE name=?", (n,))

        cols = ['hit_dice', 'hp_first_level', 'hp_next_level', 'weapon_proficiencies', 'tool_proficiencies',
                'save_proficiencies', 'skill_proficiencies', 'equipment', 'fighting_style_choice', 'second_wind']
        for c in CLASSES:
            row = conn.execute("SELECT id FROM classes WHERE name=?", (c['name'],)).fetchone()
            if row:
                cid = row['id']
                conn.execute(f"UPDATE classes SET {', '.join(k + '=?' for k in cols)} WHERE id=?", [c[k] for k in cols] + [cid])
                conn.execute("DELETE FROM class_features WHERE class_id=?", (cid,))
            else:
                cur = conn.execute(f"INSERT INTO classes (name, {', '.join(cols)}) VALUES ({', '.join('?' * (len(cols) + 1))})",
                                   [c['name']] + [c[k] for k in cols])
                cid = cur.lastrowid
            for fn, fd in c['features']:
                conn.execute("INSERT INTO class_features (class_id, feature_name, feature_description) VALUES (?, ?, ?)", (cid, fn, fd))

        for b in BACKGROUNDS:
            vals = (b['description'], b['skill_profs'], b['equipment'], b['languages'], b['feature_name'], b['feature_description'])
            row = conn.execute("SELECT id FROM backgrounds WHERE name=?", (b['name'],)).fetchone()
            if row:
                bid = row['id']
                conn.execute("UPDATE backgrounds SET description=?, skill_profs=?, equipment=?, languages=?, feature_name=?, feature_description=? WHERE id=?",
                             vals + (bid,))
                conn.execute("DELETE FROM background_choice_groups WHERE background_id=?", (bid,))
            else:
                cur = conn.execute("INSERT INTO backgrounds (name, description, skill_profs, equipment, languages, feature_name, feature_description) VALUES (?,?,?,?,?,?,?)",
                                   (b['name'],) + vals)
                bid = cur.lastrowid
            for title, options in b['groups']:
                conn.execute("INSERT INTO background_choice_groups (background_id, group_title, options_json) VALUES (?, ?, ?)",
                             (bid, title, json.dumps(options, ensure_ascii=False)))
        conn.commit()
    print(f'Классов: {len(CLASSES)}, предысторий: {len(BACKGROUNDS)} — готово.')


if __name__ == '__main__':
    main()
